package io.github.notablogger.springxpose.processor.generator;

import com.squareup.javapoet.*;
import io.github.notablogger.springxpose.annotation.FilterOperation;
import io.github.notablogger.springxpose.processor.model.EntityModel;
import io.github.notablogger.springxpose.processor.model.FilterFieldModel;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;

/**
 * Generates a {@code <Entity>FilterParams} class for entities/documents with
 * {@code @ExposeField(filterOperations = ...)} fields. It is bound from query parameters via
 * {@code @ModelAttribute} in the generated controller's {@code findAll} method.
 *
 * <p>One property per (field, operation) pair. EQ uses the field name; other operations use a
 * suffixed query parameter ({@code price_gt}) bound to a camel-case property ({@code priceGt}):
 * <ul>
 *   <li>{@code @BindParam} on the constructor parameter — Spring MVC binds {@code ?price_gt=}.</li>
 *   <li>{@code @Parameter(name = ...)} on the field — springdoc documents {@code price_gt},
 *       not the Java name.</li>
 * </ul>
 * Primitive types are boxed so absent parameters bind as {@code null} (ignored). IN / NOT_IN
 * properties are a {@code List} of the field type; IS_NULL properties are {@code Boolean}.
 *
 * <p>Example output for {@code @ExposeField(filterOperations = {EQ, GT}) BigDecimal price}:
 * <pre>
 * public final class ProductFilterParams {
 *     &#64;Parameter(name = "price", description = "price equals")
 *     private final BigDecimal price;
 *     &#64;Parameter(name = "price_gt", description = "price greater than")
 *     private final BigDecimal priceGt;
 *
 *     public ProductFilterParams(BigDecimal price, &#64;BindParam("price_gt") BigDecimal priceGt) { ... }
 *     public BigDecimal getPrice() { return price; }
 *     public BigDecimal getPriceGt() { return priceGt; }
 * }
 * </pre>
 */
public class FilterParamsGenerator {

    private static final ClassName BIND_PARAM   = ClassName.get("org.springframework.web.bind.annotation", "BindParam");
    private static final ClassName OA_PARAMETER = ClassName.get("io.swagger.v3.oas.annotations", "Parameter");

    private final ProcessingEnvironment processingEnv;

    public FilterParamsGenerator(ProcessingEnvironment processingEnv) {
        this.processingEnv = processingEnv;
    }

    public void generate(EntityModel model) {
        if (!model.hasFilters()) return;

        String entity = model.entitySimpleName();
        TypeSpec.Builder clazz = TypeSpec.classBuilder(entity + "FilterParams")
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc("Generated by spring-xpose — do not edit.\n"
                + "Query filter parameters for {@code GET /api/" + model.basePath() + "}.\n"
                + "Bound via {@code @ModelAttribute} — absent params are {@code null} (ignored).\n");
        MethodSpec.Builder ctor = MethodSpec.constructorBuilder().addModifiers(Modifier.PUBLIC);

        for (FilterFieldModel filter : model.filters()) {
            for (FilterOperation op : filter.operations()) {
                TypeName type = propertyType(filter, op);
                String property = filter.propertyName(op);
                String param    = filter.paramName(op);

                clazz.addField(FieldSpec.builder(type, property, Modifier.PRIVATE, Modifier.FINAL)
                    .addAnnotation(AnnotationSpec.builder(OA_PARAMETER)
                        .addMember("name", "$S", param)
                        .addMember("description", "$S", describe(filter, op))
                        .build())
                    .build());

                ParameterSpec.Builder ctorParam = ParameterSpec.builder(type, property);
                if (!param.equals(property)) {
                    ctorParam.addAnnotation(AnnotationSpec.builder(BIND_PARAM)
                        .addMember("value", "$S", param)
                        .build());
                }
                ctor.addParameter(ctorParam.build())
                    .addStatement("this.$L = $L", property, property);

                clazz.addMethod(MethodSpec.methodBuilder(filter.getterName(op))
                    .addModifiers(Modifier.PUBLIC)
                    .returns(type)
                    .addStatement("return $L", property)
                    .build());
            }
        }
        clazz.addMethod(ctor.build());

        try {
            JavaFile.builder(model.packageName() + ".generated", clazz.build())
                .addFileComment("Generated by spring-xpose — do not edit")
                .build()
                .writeTo(processingEnv.getFiler());
        } catch (IOException e) {
            throw new RuntimeException("Failed to write FilterParams for " + model.entitySimpleName(), e);
        }
    }

    /**
     * Java type of one filter property: the boxed field type, a {@code List} of it for IN / NOT_IN
     * (Spring splits {@code ?status_in=A,B} into the list) — of the element type for collection
     * fields — or {@code Boolean} for IS_NULL.
     */
    private static TypeName propertyType(FilterFieldModel filter, FilterOperation op) {
        TypeName fieldType = TypeName.get(filter.type()).box();
        return switch (op) {
            case IN, NOT_IN -> ParameterizedTypeName.get(ClassName.get("java.util", "List"),
                filter.isCollection() ? TypeName.get(filter.elementType()) : fieldType);
            case IS_NULL    -> TypeName.BOOLEAN.box();
            default         -> fieldType;
        };
    }

    /** OpenAPI description for one filter parameter. */
    private static String describe(FilterFieldModel filter, FilterOperation op) {
        String field = filter.name();
        if (filter.isCollection()) {
            return switch (op) {
                case IN      -> field + " has any of (comma-separated)";
                case NOT_IN  -> field + " has none of (comma-separated)";
                case IS_NULL -> "true: " + field + " is null or empty, false: " + field + " has elements";
                default      -> throw new IllegalStateException(op + " on collection " + field);
            };
        }
        return switch (op) {
            case EQ      -> field + " equals";
            case NE      -> field + " not equal (includes null)";
            case GT      -> field + " greater than";
            case GTE     -> field + " greater than or equal";
            case LT      -> field + " less than";
            case LTE     -> field + " less than or equal";
            case LIKE    -> field + " contains (case-insensitive)";
            case IN      -> field + " is one of (comma-separated)";
            case NOT_IN  -> field + " is none of (comma-separated, includes null)";
            case IS_NULL -> "true: " + field + " is null, false: " + field + " is set";
        };
    }
}
