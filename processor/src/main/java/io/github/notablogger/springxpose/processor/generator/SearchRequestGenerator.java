package io.github.notablogger.springxpose.processor.generator;

import com.squareup.javapoet.*;
import io.github.notablogger.springxpose.annotation.FilterOperation;
import io.github.notablogger.springxpose.processor.model.EntityModel;
import io.github.notablogger.springxpose.processor.model.FilterFieldModel;

import javax.annotation.processing.ProcessingEnvironment;
import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

/**
 * Generates a {@code <Entity>SearchRequest} class for entities/documents exposing
 * {@code Operation.SEARCH}. It is the JSON request body of the generated controller's
 * {@code POST /api/<path>/search} method.
 *
 * <p>One property per (field, operation) pair. EQ uses the field name; other operations use a
 * suffixed JSON key ({@code price_gt}) mapped to a camel-case property ({@code priceGt}):
 * <ul>
 *   <li>{@code @JsonProperty} on the field — Jackson reads {@code "price_gt"} and springdoc
 *       documents that key, not the Java name.</li>
 *   <li>{@code @Schema(description = ...)} on the field — the description in the OpenAPI schema.</li>
 *   <li>A {@code @JsonAnySetter} that throws — a key the class does not declare (a typo, or an
 *       operation the field does not support) fails with {@code 400} instead of being ignored,
 *       whatever the application's {@code FAIL_ON_UNKNOWN_PROPERTIES} setting.</li>
 * </ul>
 * Primitive types are boxed so absent keys are {@code null} (ignored). IN / NOT_IN properties
 * are a {@code List} of the field type; IS_NULL properties are {@code Boolean}.
 *
 * <p>Example output for {@code @ExposeField(filterOperations = {EQ, GT}) BigDecimal price}:
 * <pre>
 * public final class ProductSearchRequest {
 *     &#64;JsonProperty("price")
 *     &#64;Schema(description = "price equals")
 *     private BigDecimal price;
 *     &#64;JsonProperty("price_gt")
 *     &#64;Schema(description = "price greater than")
 *     private BigDecimal priceGt;
 *
 *     public BigDecimal getPrice() { return price; }
 *     public BigDecimal getPriceGt() { return priceGt; }
 *
 *     &#64;JsonAnySetter
 *     void rejectUnknownKey(String key, Object value) { throw new IllegalArgumentException(...); }
 * }
 * </pre>
 */
public class SearchRequestGenerator {

    private static final ClassName JSON_PROPERTY   = ClassName.get("com.fasterxml.jackson.annotation", "JsonProperty");
    private static final ClassName JSON_ANY_SETTER = ClassName.get("com.fasterxml.jackson.annotation", "JsonAnySetter");
    private static final ClassName OA_SCHEMA       = ClassName.get("io.swagger.v3.oas.annotations.media", "Schema");

    private final ProcessingEnvironment processingEnv;

    public SearchRequestGenerator(ProcessingEnvironment processingEnv) {
        this.processingEnv = processingEnv;
    }

    public void generate(EntityModel model) {
        if (!model.searchable()) return;

        String entity = model.entitySimpleName();
        TypeSpec.Builder clazz = TypeSpec.classBuilder(entity + "SearchRequest")
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addAnnotation(AnnotationSpec.builder(OA_SCHEMA)
                .addMember("description", "$S", "Search filters for " + entity
                    + ". Every key is optional; keys are combined with AND. Unknown keys are rejected.")
                .build())
            .addJavadoc("Generated by spring-xpose — do not edit.\n"
                + "JSON request body of {@code POST /api/" + model.basePath() + "/search}.\n"
                + "Absent keys are {@code null} (ignored); unknown keys are rejected with 400.\n");

        List<String> keys = new ArrayList<>();
        for (FilterFieldModel filter : model.filters()) {
            for (FilterOperation op : filter.operations()) {
                TypeName type = propertyType(filter, op);
                String property = filter.propertyName(op);
                String key      = filter.keyName(op);
                keys.add(key);

                clazz.addField(FieldSpec.builder(type, property, Modifier.PRIVATE)
                    .addAnnotation(AnnotationSpec.builder(JSON_PROPERTY)
                        .addMember("value", "$S", key)
                        .build())
                    .addAnnotation(AnnotationSpec.builder(OA_SCHEMA)
                        .addMember("description", "$S", describe(filter, op))
                        .build())
                    .build());

                clazz.addMethod(MethodSpec.methodBuilder(filter.getterName(op))
                    .addModifiers(Modifier.PUBLIC)
                    .returns(type)
                    .addStatement("return $L", property)
                    .build());
            }
        }

        // Jackson routes every key without a property here — reject it rather than ignore it
        String allowed = keys.isEmpty() ? "none (no field declares filterOperations)" : String.join(", ", keys);
        clazz.addMethod(MethodSpec.methodBuilder("rejectUnknownKey")
            .addAnnotation(JSON_ANY_SETTER)
            .addParameter(String.class, "key")
            .addParameter(Object.class, "value")
            .addStatement("throw new $T($S + key + $S)", IllegalArgumentException.class,
                "Unknown search key '", "' for " + entity + " — allowed keys: " + allowed)
            .build());

        try {
            JavaFile.builder(model.packageName() + ".generated", clazz.build())
                .addFileComment("Generated by spring-xpose — do not edit")
                .build()
                .writeTo(processingEnv.getFiler());
        } catch (IOException e) {
            throw new RuntimeException("Failed to write SearchRequest for " + model.entitySimpleName(), e);
        }
    }

    /**
     * Java type of one filter property: the boxed field type, a {@code List} of it for IN / NOT_IN
     * (a JSON array) — of the element type for collection fields — or {@code Boolean} for IS_NULL.
     */
    private static TypeName propertyType(FilterFieldModel filter, FilterOperation op) {
        TypeName fieldType = TypeName.get(filter.type()).box();
        return switch (op) {
            case IN, NOT_IN -> ParameterizedTypeName.get(ClassName.get("java.util", "List"),
                filter.isCollection() ? TypeName.get(filter.elementType()) : fieldType);
            case IS_NULL    -> TypeName.BOOLEAN.box();
            default         -> fieldType;
        };
    }

    /** OpenAPI description for one search key. */
    private static String describe(FilterFieldModel filter, FilterOperation op) {
        String field = filter.isRelation() && !filter.isCollection() ? filter.name() + " id" : filter.name();
        if (filter.isCollection()) {
            String values = filter.isRelation() ? " the ids" : "";
            return switch (op) {
                case IN      -> field + " has any of" + values;
                case NOT_IN  -> field + " has none of" + values;
                case IS_NULL -> "true: " + field + " is null or empty, false: " + field + " has elements";
                default      -> throw new IllegalStateException(op + " on collection " + field);
            };
        }
        return switch (op) {
            case EQ      -> field + " equals";
            case NE      -> field + " not equal (includes null)";
            case GT      -> field + " greater than";
            case GTE     -> field + " greater than or equal";
            case LT      -> field + " less than";
            case LTE     -> field + " less than or equal";
            case LIKE    -> field + " contains (case-insensitive)";
            case IN      -> field + " is one of";
            case NOT_IN  -> field + " is none of (includes null)";
            case IS_NULL -> "true: " + field + " is null, false: " + field + " is set";
        };
    }
}
